// Run after npm run build: node_modules/electron/dist/electron scripts/test-sales-ui.cjs
const { app, BrowserWindow } = require('electron')
const { join } = require('node:path')
const { mkdtempSync, writeFileSync, rmSync } = require('node:fs')
const { tmpdir } = require('node:os')
const assert = require('node:assert/strict')
const profile = mkdtempSync(join(tmpdir(), 'hardware-sales-ui-'))
app.setPath('userData', profile)
app.disableHardwareAcceleration()
let window
const errors = []
const evaluate = async (code) => {
  try { return await window.webContents.executeJavaScript(code) }
  catch (error) { throw new Error(`Renderer evaluation failed: ${code}`, { cause: error }) }
}
const delay = (ms = 80) => new Promise((resolve) => setTimeout(resolve, ms))
const click = async (text) => {
  for (let attempt = 0; attempt < 60; attempt++) {
    const ready = await evaluate(`(() => { const b = [...document.querySelectorAll('button')].find(b => b.textContent.trim() === ${JSON.stringify(text)}); return !!b && !b.disabled })()`)
    if (ready) break
    await delay(50)
  }
  await evaluate(`(() => { const b = [...document.querySelectorAll('button')].find(b => b.textContent.trim() === ${JSON.stringify(text)}); if (!b || b.disabled) throw new Error('Button unavailable: ' + ${JSON.stringify(text)}); b.click() })()`)
  await delay()
}
const setInput = async (selector, value) => {
  await evaluate(`(() => { const el = document.querySelector(${JSON.stringify(selector)}); if (!el) throw new Error('Missing input'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(el, ${JSON.stringify(value)}); el.dispatchEvent(new Event('input', { bubbles: true })); })()`)
  await delay()
}
const body = () => evaluate('document.body.innerText')
app.whenReady().then(async () => {
  window = new BrowserWindow({ width: 1200, height: 1200, show: false, webPreferences: { preload: join(__dirname, 'sales-ui-preload.cjs'), contextIsolation: true, nodeIntegration: false, sandbox: false, backgroundThrottling: false, offscreen: true } })
  window.webContents.on('console-message', (event) => { if (event.level === 'error') errors.push(event.message) })
  await window.loadFile(join(__dirname, '../out/renderer/index.html'))
  await delay()
  await click('Vendas')
  await delay(350)
  await click('Adicionar')
  assert.match(await body(), /Carrinho \(1\)/)
  await setInput('article input', '2')
  await click('Caixa')
  await click('Vendas')
  await delay(350)
  assert.equal(await evaluate("document.querySelector('article input').value"), '2')
  await click('Cancelar venda atual')
  assert.match(await body(), /Descartar todos os itens/)
  await click('Continuar venda')
  assert.match(await body(), /Carrinho \(1\)/)
  await click('Cancelar venda atual')
  await click('Descartar venda')
  assert.match(await body(), /Carrinho \(0\)/)
  // An old slow search must not overwrite a newer response.
  await setInput('[aria-label="Buscar produto"]', 'Martelo')
  await click('Buscar')
  await setInput('[aria-label="Buscar produto"]', 'Elétrica')
  await click('Buscar')
  await delay(500)
  assert.equal(await evaluate("document.querySelector('li p').textContent"), 'Cabo flexível')
  await click('Adicionar')
  await setInput('article input', '0,5')
  await click('Adicionar pagamento')
  await evaluate('window.salesTest.fail(true)')
  await click('Finalizar venda')
  await delay(400)
  assert.match(await body(), /Estoque mudou/)
  assert.match(await body(), /Carrinho \(1\)/)
  await evaluate('window.salesTest.fail(false)')
  const before = await evaluate('window.salesTest.calls()')
  await evaluate("(() => { const b = [...document.querySelectorAll('button')].find(b => b.textContent === 'Finalizar venda'); b.click(); b.click(); })()")
  await delay(50)
  assert.equal(await evaluate("[...document.querySelectorAll('nav button')].every(b => b.disabled)"), true)
  await delay(450)
  assert.equal(await evaluate('window.salesTest.calls()'), before + 1)
  assert.match(await body(), /finalizada com sucesso/)
  assert.match(await body(), /Carrinho \(0\)/)
  await click('Adicionar')
  await click('Adicionar pagamento')
  // A refresh failure after commit must retain the success notice and empty cart.
  await evaluate('window.salesTest.failRefresh(true)')
  await click('Finalizar venda')
  await delay(450)
  assert.match(await body(), /finalizada com sucesso/)
  assert.match(await body(), /Falha ao atualizar caixa/)
  assert.match(await body(), /Carrinho \(0\)/)
  await evaluate('window.salesTest.failRefresh(false); window.salesTest.setOpen(false)')
  await click('Atualizar')
  await delay(350)
  assert.match(await body(), /Abra um caixa/)
  await click('Adicionar')
  assert.equal(await evaluate("[...document.querySelectorAll('button')].find(b => b.textContent === 'Finalizar venda').disabled"), true)
  await evaluate('window.salesTest.setOpen(true)')
  await click('Atualizar')
  await delay(350)
  await setInput('[aria-label="Buscar produto"]', '')
  await click('Buscar')
  await delay(100)
  await click('Adicionar')
  await setInput('article input', '0,5')
  await setInput('article label:nth-child(2) input', '6,00')
  await setInput('article label:nth-child(3) input', '0,50')
  await setInput('input.max-w-36', '1,00')
  await evaluate(`(() => { const select = document.querySelector('select'); select.value = '1'; select.dispatchEvent(new Event('change', { bubbles: true })); })()`)
  await click('Adicionar pagamento')
  await setInput('input[value="26,50"]', '10,00')
  await click('Adicionar pagamento')
  await evaluate(`(() => { const selects = document.querySelectorAll('select'); const select = selects[selects.length - 1]; select.value = 'pix'; select.dispatchEvent(new Event('change', { bubbles: true })); })()`)
  await delay(200)
  writeFileSync(join(tmpdir(), 'hardware-pdv.png'), (await window.webContents.capturePage()).toPNG())
  window.setSize(900, 700)
  await delay()
  assert.equal(await evaluate('document.documentElement.scrollWidth <= window.innerWidth'), true)
  await click('Finalizar venda')
  await delay(450)
  const submitted = await evaluate('window.salesTest.lastInput()')
  assert.equal(submitted.customerId, 1)
  assert.equal(submitted.discountInCents, 100)
  assert.deepEqual(submitted.payments, [{ method: 'cash', amountInCents: 1000 }, { method: 'pix', amountInCents: 1650 }])
  assert.equal(submitted.items[0].unitPriceInCents, 600)
  assert.equal(submitted.items[0].discountInCents, 50)
  assert.match(await body(), /finalizada com sucesso/)
  assert.deepEqual(errors, [])
  console.log('PDV UI smoke passed: navigation, cancellation, stale search, decimal quantity, failure preservation, duplicate click, refresh failure, closed register, responsive layout. Screenshot: /tmp/hardware-pdv.png')
}).catch(async (error) => { console.error(error); console.error(errors); console.error(await body()); process.exitCode = 1 }).finally(() => {
  if (window) window.destroy()
  app.exit(process.exitCode || 0)
})
app.on('will-quit', () => { try { rmSync(profile, { recursive: true, force: true }) } catch {} })
